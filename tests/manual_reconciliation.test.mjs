import assert from 'node:assert/strict';
import {newLedgerState,activeLedger} from '../ledger_tree.js';
import {cloneF24,usableF24} from '../movement_edits.js';
import {link,unlink,syncLinks} from '../manual_reconciliation.js';
import {reconcile} from '../f24_ade.js';
import {buildStDraft} from '../st_draft.js';
const ledger=newLedgerState([{name:'TEST',code:'1040',date:'31/07/25',amount:20926}]);
const payments=cloneF24([{date:'16/09/2025',code:'1040',month:'08',year:'2025',debit:20928,credit:0}]);
const rows=()=>reconcile(activeLedger(ledger),usableF24(payments),'2025');
const st=()=>buildStDraft(activeLedger(ledger),usableF24(payments),'2025').rows;
assert.equal(rows().length,2);
link(ledger[0],usableF24(payments));
assert.equal(ledger[0].period,'07/2025');assert.equal(ledger[0].source.date,'31/07/25');
assert.equal(payments[0].original.month,'08');assert.equal(rows().length,1);
assert.equal(rows()[0].difference,2);assert.equal(st().length,1);
assert.equal(st()[0].point1,'08/2025');assert.equal(st()[0].point2,20926);assert.equal(st()[0].point7,20928);
assert.throws(()=>link(ledger[0],usableF24(payments)));
ledger[0].amount=20925;assert.equal(st()[0].point2,20925);
ledger[0].excluded=true;assert.equal(activeLedger(ledger).length,0);
ledger[0].excluded=false;assert.equal(st().length,1);
unlink(ledger[0]);assert.equal(rows().length,2);assert.equal(st().length,2);
link(ledger[0],usableF24(payments));payments[0].assignedMonth='09';
syncLinks(ledger,usableF24(payments));assert.equal(ledger[0].stPeriod,undefined);
assert.equal(ledger[0].amount,20925);assert.equal(payments[0].debit,20928);
console.log('Manual reconciliation tests passed');
